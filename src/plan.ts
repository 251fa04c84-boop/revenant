import { firstInstallable } from './replacements';
import type { Finding, Summary } from './types';

const SKIP_PLAN: ReadonlySet<string> = new Set(['alive', 'unknown']);

export interface PlanOptions {
  manifestName?: string;
  now?: Date;
}

/** Actionable findings: things we have a concrete replacement for. */
export function actionable(findings: readonly Finding[]): Finding[] {
  return findings.filter((f) => !SKIP_PLAN.has(f.verdict) && f.replacement);
}

/** Shell commands that swap every dependency we have an installable replacement for. */
export function migrationCommands(findings: readonly Finding[]): string[] {
  const remove = new Set<string>();
  const addProd: string[] = [];
  const addDev: string[] = [];
  for (const f of actionable(findings)) {
    if (f.dep.kind === 'peerDependencies') continue; // peers are declared, not installed, by this project
    const alt = f.replacement ? firstInstallable(f.replacement.alts) : undefined;
    remove.add(f.dep.name);
    if (alt?.pkg && alt.pkg !== f.dep.name) {
      (f.dep.kind === 'devDependencies' ? addDev : addProd).push(alt.pkg);
    }
  }
  const cmds: string[] = [];
  if (remove.size) cmds.push(`npm uninstall ${[...remove].join(' ')}`);
  if (addProd.length) cmds.push(`npm install ${[...new Set(addProd)].join(' ')}`);
  if (addDev.length) cmds.push(`npm install -D ${[...new Set(addDev)].join(' ')}`);
  return cmds;
}

export function buildMarkdown(
  findings: readonly Finding[],
  summary: Summary,
  opts: PlanOptions = {},
): string {
  const date = (opts.now ?? new Date()).toISOString().slice(0, 10);
  const title = opts.manifestName ? ` for ${opts.manifestName}` : '';
  const out: string[] = [];
  out.push(`# Resurrection plan${title}`);
  out.push('');
  out.push(`_Generated by Revenant on ${date}._`);
  out.push('');
  out.push(
    `**Health: ${summary.score}/100 (${summary.label})**: ${summary.counts.dead} dead, ${summary.counts.restless} restless, ` +
      `${summary.counts.fading} fading, ${summary.counts.alive} alive, ${summary.counts.unknown} unknown.`,
  );
  out.push('');

  const todo = findings.filter((f) => f.verdict === 'dead' || f.verdict === 'restless' || f.verdict === 'fading');
  if (todo.length === 0) {
    out.push('Nothing to resurrect. Every dependency looks healthy.');
    return `${out.join('\n')}\n`;
  }

  const cmds = migrationCommands(findings);
  if (cmds.length) {
    out.push('## Quick migration');
    out.push('');
    out.push('```sh');
    out.push(...cmds);
    out.push('```');
    out.push('');
    out.push('Then update imports and run your tests. See the per-package notes below for API differences.');
    out.push('');
  }

  out.push('## Findings');
  out.push('');
  for (const f of todo) {
    out.push(`### ${f.dep.name} (${f.verdict})`);
    out.push('');
    for (const r of f.reasons) out.push(`- ${r}`);
    if (f.replacement) {
      out.push(`- **Replace with:** ${f.replacement.alts.map((a) => a.label).join(' · ')}`);
      out.push(`- **Effort:** ${f.replacement.effort}`);
      out.push(`- **Notes:** ${f.replacement.notes}`);
      if (f.replacement.snippet) {
        out.push('');
        out.push('```diff');
        for (const line of f.replacement.snippet.before.split('\n')) out.push(`- ${line}`);
        for (const line of f.replacement.snippet.after.split('\n')) out.push(`+ ${line}`);
        out.push('```');
      }
    } else if (f.verdict === 'dead' || f.verdict === 'restless') {
      out.push('- **Replace with:** no curated replacement. Search npm for an actively maintained alternative, or check whether a fork exists.');
    }
    out.push('');
  }
  return `${out.join('\n')}\n`;
}
